    /** @return array<string, list<Glob>> each group's globs, by why no result depends on it */
    public static function groups(): array
    {
        return array_map(static fn(array $globs): array => array_map(Glob::of(...), $globs), self::GROUPS);
    }

    /** @return list<Glob> */
    public static function globs(): array
    {
        return array_merge(...array_values(self::groups()));
    }
