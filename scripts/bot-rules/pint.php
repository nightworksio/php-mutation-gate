<?php

declare(strict_types=1);

// Prints .github/bot/rules/pint.json: every fixer the locked Pint can apply,
// with php-cs-fixer's own summary and the page of its rule reference (ADR-0019,
// decision 7). `composer bot:rules` writes it, and the Unit suite fails while
// the committed file differs. It runs on its own, because Pint's PHAR carries
// its own copies of packages this project also installs.

Phar::loadPhar(dirname(__DIR__, 2) . '/vendor/laravel/pint/builds/pint', 'pint.phar');

require 'phar://pint.phar/vendor/autoload.php';

use PhpCsFixer\Fixer\FixerInterface;
use PhpCsFixer\FixerFactory;

$factory = new FixerFactory();
$factory->registerBuiltInFixers();
$fixers = $factory->getFixers();

$own = new RecursiveIteratorIterator(new RecursiveDirectoryIterator('phar://pint.phar/app/Fixers'));

foreach ($own as $file) {
    if (! str_ends_with($file->getFilename(), 'Fixer.php')) {
        continue;
    }

    $class = sprintf('App\\Fixers\\%s', str_replace(['/', '.php'], ['\\', ''], substr($file->getPathname(), strlen('phar://pint.phar/app/Fixers/'))));

    $reflection = class_exists($class) ? new ReflectionClass($class) : null;

    if ($reflection?->implementsInterface(FixerInterface::class) && ($reflection->getConstructor()?->getNumberOfRequiredParameters() ?? 0) === 0) {
        $fixers[] = $reflection->newInstance();
    }
}

$rules = [];

foreach ($fixers as $fixer) {
    $group = preg_match('/^PhpCsFixer\\\\Fixer\\\\(\w+)\\\\/', $fixer::class, $in) === 1
        ? strtolower((string) preg_replace('/(?<!^)[A-Z]/', '_$0', $in[1]))
        : '';
    $rules[$fixer->getName()] = [
        'says' => trim($fixer->getDefinition()->getSummary()),
        'link' => $group === '' ? '' : sprintf('https://cs.symfony.com/doc/rules/%s/%s.html', $group, $fixer->getName()),
    ];
}

ksort($rules);

// The Pint these fixers are from, as Composer installed it, so a table is only
// held to the Pint it was written from.
$installed = json_decode((string) file_get_contents(dirname(__DIR__, 2) . '/vendor/composer/installed.json'), true);
$version = '';

foreach (is_array($installed) ? $installed['packages'] : [] as $package) {
    $version = $package['name'] === 'laravel/pint' ? $package['version'] : $version;
}

echo json_encode(
    ['$comment' => 'Generated by scripts/bot-rules/pint.php from the locked Pint; run composer bot:rules.', 'version' => $version, 'rules' => $rules],
    JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR,
), "\n";
