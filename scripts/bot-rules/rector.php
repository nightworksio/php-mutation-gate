<?php

declare(strict_types=1);

// Prints .github/bot/rules/rector.json: every rule the locked Rector ships,
// with Rector's own description and the page of its rule reference (ADR-0019,
// decision 7). `composer bot:rules` writes it, and the Unit suite fails while
// the committed file differs.

$rector = dirname(__DIR__, 2) . '/vendor/rector/rector';

require dirname(__DIR__, 2) . '/vendor/autoload.php';
require $rector . '/bootstrap.php';

use Rector\Contract\Rector\RectorInterface;
use Rector\PostRector\Contract\Rector\PostRectorInterface;

// Rector runs these after the rules, and they carry no description of their own.
$rules = [
    'Rector\\PostRector\\Rector\\ClassRenamingPostRector' => ['says' => 'Rename a class a rule renamed wherever it is named.', 'link' => ''],
    'Rector\\PostRector\\Rector\\DocblockNameImportingPostRector' => ['says' => 'Import a name a docblock writes in full.', 'link' => ''],
    'Rector\\PostRector\\Rector\\NameImportingPostRector' => ['says' => 'Import a name the code writes in full.', 'link' => ''],
    'Rector\\PostRector\\Rector\\UnusedImportRemovingPostRector' => ['says' => 'Remove a use statement nothing refers to.', 'link' => ''],
    'Rector\\PostRector\\Rector\\UseAddingPostRector' => ['says' => 'Add the use statement a rule needs.', 'link' => ''],
];

foreach (['rules', 'src'] as $tree) {
    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator(sprintf('%s/%s', $rector, $tree), FilesystemIterator::SKIP_DOTS));

    foreach ($files as $file) {
        $source = str_ends_with($file->getFilename(), 'Rector.php') ? (string) file_get_contents($file->getPathname()) : '';

        if (preg_match('/^namespace ([^;]+);/m', $source, $namespace) !== 1 || preg_match('/^(?:final |abstract |readonly )*class (\w+)/m', $source, $class) !== 1) {
            continue;
        }

        $reflection = new ReflectionClass(sprintf('%s\\%s', $namespace[1], $class[1]));
        $isRule = $reflection->implementsInterface(RectorInterface::class) || $reflection->implementsInterface(PostRectorInterface::class);

        if ($reflection->isAbstract() || ! $isRule || ! $reflection->hasMethod('getRuleDefinition')) {
            continue;
        }

        $name = $reflection->getShortName();
        $rules[$reflection->getName()] = [
            'says' => trim($reflection->newInstanceWithoutConstructor()->getRuleDefinition()->getDescription()),
            'link' => $tree === 'rules'
                ? sprintf('https://getrector.com/rule-detail/%s', strtolower((string) preg_replace('/(?<!^)[A-Z]/', '-$0', $name)))
                : '',
        ];
    }
}

ksort($rules);

// The Rector these rules are from, as Composer installed it, so a table is only
// held to the Rector it was written from.
$installed = json_decode((string) file_get_contents(dirname(__DIR__, 2) . '/vendor/composer/installed.json'), true);
$version = '';

foreach (is_array($installed) ? $installed['packages'] : [] as $package) {
    $version = $package['name'] === 'rector/rector' ? $package['version'] : $version;
}

echo json_encode(
    [
        '$comment' => 'Generated by scripts/bot-rules/rector.php from the locked Rector; run composer bot:rules.',
        'version' => $version,
        'rules' => $rules,
    ],
    JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR,
), "\n";
